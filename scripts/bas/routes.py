"""Route names for /bas: GTFS static (data.gov.my) -> src/data/bas-routes.ts.

Live vehicle positions only carry a route_id ("U3000"); riders know the route by
its short name ("300") and its ends ("Terminal Maluri ~ Lebuh Ampang"). Routes
change rarely - re-run this when an operator changes its network:

    python3 scripts/bas/routes.py
"""

import csv
import io
import json
import pathlib
import urllib.request
import zipfile

from feeds import FEEDS  # same list as src/lib/bas.ts

OUT = pathlib.Path(__file__).resolve().parents[2] / "src/data/bas-routes.ts"
API = "https://api.data.gov.my/gtfs-static/"

routes = {}
for feed in FEEDS:
    url = API + feed["static"]
    try:
        with urllib.request.urlopen(url, timeout=120) as res:
            z = zipfile.ZipFile(io.BytesIO(res.read()))
    except (zipfile.BadZipFile, OSError) as e:
        # No usable static feed: /bas falls back to the raw route_id.
        print(f"{feed['id']}: skipped ({e})")
        continue
    rows = csv.DictReader(io.TextIOWrapper(z.open("routes.txt"), encoding="utf-8-sig"))
    routes[feed["id"]] = {
        r["route_id"]: [r.get("route_short_name", "").strip(), r.get("route_long_name", "").strip()]
        for r in rows
    }
    print(f"{feed['id']}: {len(routes[feed['id']])} routes")

OUT.write_text(
    "// GENERATED by scripts/bas/routes.py from data.gov.my GTFS static - do not edit.\n"
    "// feed id -> route_id -> [short name, long name]\n"
    f"export const BAS_ROUTES: Record<string, Record<string, [string, string]>> = {json.dumps(routes, ensure_ascii=False, indent=0)};\n"
)
print("wrote", OUT)
