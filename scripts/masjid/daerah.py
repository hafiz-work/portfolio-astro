#!/usr/bin/env python3
"""Generate src/data/masjid-daerah.ts - SISMIM (JAKIM) states and districts for /waktu-solat/masjid.

SISMIM's own lookup (masjid.islam.gov.my/daerah?ids=NN, JSON) - the same codes its list
page takes as `negeri` / `daerah`. The page validates ?negeri= / ?daerah= against this
file before they reach the upstream URL. Districts rarely change; re-run when SISMIM adds one.

Run: python3 scripts/masjid/daerah.py   (never edit the generated file by hand)
"""
import json
import urllib.request
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "src/data/masjid-daerah.ts"
URL = "https://masjid.islam.gov.my/daerah?ids={}"
# SISMIM's codes; names written out (SISMIM prints "N. SEMBILAN").
NEGERI = {
    "01": "Johor", "02": "Kedah", "03": "Kelantan", "04": "Melaka", "05": "Negeri Sembilan",
    "06": "Pahang", "07": "Pulau Pinang", "08": "Perak", "09": "Perlis", "10": "Selangor",
    "11": "Terengganu", "12": "Sabah", "13": "Sarawak", "14": "W.P. Kuala Lumpur",
    "15": "W.P. Labuan", "16": "W.P. Putrajaya",
}


def get(code: str):
    req = urllib.request.Request(URL.format(code), headers={"User-Agent": "hafizbahtiar.com masjid-daerah generator"})
    with urllib.request.urlopen(req, timeout=60) as res:
        return json.load(res)


def label(name: str) -> str:
    name = " ".join(name.split())
    return "Tiada maklumat daerah" if name == "TIADA MAKLUMAT DAERAH" else name.title()


rows = []
for code, nama in NEGERI.items():
    daerah = [d for d in get(code) if d.get("is_active") == 1 and d["id_daerah"].startswith(code)]
    assert daerah, f"no districts for {code}"
    rows.append((code, nama, sorted(((d["id_daerah"], label(d["descr_daerah"])) for d in daerah), key=lambda d: d[0])))

lines = [
    "// GENERATED by scripts/masjid/daerah.py - do not edit by hand.",
    "// SISMIM (JAKIM) state + district codes, from masjid.islam.gov.my/daerah.",
    f"// {len(rows)} states, {sum(len(r[2]) for r in rows)} districts.",
    "export interface Negeri {",
    "  code: string;",
    "  name: string;",
    "  daerah: { code: string; name: string }[];",
    "}",
    "",
    "export const NEGERI: Negeri[] = [",
]
for code, nama, daerah in rows:
    lines.append(f"  {{ code: {json.dumps(code)}, name: {json.dumps(nama)}, daerah: [")
    lines += [f"    {{ code: {json.dumps(c)}, name: {json.dumps(n)} }}," for c, n in daerah]
    lines.append("  ] },")
lines.append("];")
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {OUT} ({sum(len(r[2]) for r in rows)} districts)")
