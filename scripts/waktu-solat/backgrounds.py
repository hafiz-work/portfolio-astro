"""Standardise the Paparan Masjid background photos.

Each source photo becomes up to two WebP files, centre-cropped (cover) to:
  - landscape 1920x1080 (16:9)  - TV / landscape screens
  - portrait  1080x1920 (9:16)  - phones / tablets held upright
An orientation is skipped when the crop would need more than MAX_UPSCALE
(no blurry backgrounds). Writes public/images/waktu-solat/bg/<id>-<orientation>.webp
and src/data/paparan-backgrounds.ts (the list the Tetapan dialog shows).

The originals stay out of the repo (several MB each). To add a photo: drop it in
SRC, add a PHOTOS row, re-run:

    python3 scripts/waktu-solat/backgrounds.py [SRC]   # SRC defaults to ~/Downloads
"""
import json, os, sys
from PIL import Image, ImageOps

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Downloads")
OUT = os.path.join(ROOT, "public", "images", "waktu-solat", "bg")
DATA = os.path.join(ROOT, "src", "data", "paparan-backgrounds.ts")

SIZES = {"landscape": (1920, 1080), "portrait": (1080, 1920)}
MAX_UPSCALE = 1.18
QUALITY = 78

# (source file, id, label[, focus_x]). Labels only name places that are certain.
# focus_x (0-1, default 0.5): horizontal point the portrait crop keeps in view.
PHOTOS = [
    ("ali-muhammad-_YkEkI8tWrQ-unsplash.jpg", "masjid-faisal", "Masjid Faisal"),
    ("stacey-franco-ex9KQrN1mj0-unsplash.jpg", "kubah-as-sakhrah", "Kubah As-Sakhrah"),
    ("juan-camilo-guarin-p-njEXjDmYn8w-unsplash.jpg", "masjid-sheikh-zayed", "Masjid Sheikh Zayed"),
    ("david-rodrigo-kZ1zThg6G40-unsplash.jpg", "masjid-senja-pantulan", "Masjid waktu senja"),
    ("faruk-kaymak-CNVvDjVDiVI-unsplash.jpg", "siling-kubah", "Siling kubah"),
    ("sulthan-auliya-rzzS0_pMsD0-unsplash.jpg", "masjid-nabawi", "Masjid Nabawi", 0.7),  # green dome
    ("fahrul-azmi-gyKmF0vnfBs-unsplash.jpg", "masjid-langit-senja", "Masjid & langit senja"),
]


def cover(img: Image.Image, size: tuple[int, int], focus_x: float) -> Image.Image | None:
    """Centre-crop to the target aspect, then resize; None if that needs too much upscaling."""
    tw, th = size
    w, h = img.size
    scale = max(tw / w, th / h)
    if scale > MAX_UPSCALE:
        return None
    return ImageOps.fit(img, size, Image.LANCZOS, centering=(focus_x, 0.5))


def main() -> None:
    os.makedirs(OUT, exist_ok=True)
    entries = []
    for file, pid, label, *rest in PHOTOS:
        focus_x = rest[0] if rest else 0.5
        path = os.path.join(SRC, file)
        if not os.path.exists(path):
            sys.exit(f"missing source: {path}")
        img = ImageOps.exif_transpose(Image.open(path)).convert("RGB")
        made = {}
        for orient, size in SIZES.items():
            out = cover(img, size, focus_x)
            dest = os.path.join(OUT, f"{pid}-{orient}.webp")
            if out is None:
                if os.path.exists(dest):
                    os.remove(dest)
                continue
            out.save(dest, "WEBP", quality=QUALITY, method=6)
            made[orient] = True
            print(f"{pid}-{orient}.webp  {os.path.getsize(dest) // 1024} KB")
        entries.append({"id": pid, "label": label, "landscape": "landscape" in made, "portrait": "portrait" in made})

    with open(DATA, "w") as f:
        f.write("// Generated by scripts/waktu-solat/backgrounds.py - do not edit by hand.\n")
        f.write("// Files: public/images/waktu-solat/bg/<id>-<landscape|portrait>.webp\n")
        f.write("export interface PaparanBackground {\n  id: string;\n  label: string;\n  landscape: boolean;\n  portrait: boolean;\n}\n\n")
        f.write(f"export const PAPARAN_BACKGROUNDS: PaparanBackground[] = {json.dumps(entries, indent=2, ensure_ascii=False)};\n")
    print(f"wrote {os.path.relpath(DATA, ROOT)} ({len(entries)} photos)")


if __name__ == "__main__":
    main()
