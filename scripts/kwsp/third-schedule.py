"""KWSP Third Schedule (Jadual Ketiga) PDF -> src/data/kwsp/2025-10.ts.

Source: docs/sources/kwsp/third-schedule-2025-10-01.pdf, downloaded by hand from
kwsp.gov.my (the site blocks automated downloads) - "Effective 1 October 2025".
Every band row is "From A to B employer employee total"; the script refuses to
write anything if a row's employer + employee != total, if bands have gaps, or if
the PDF is not the expected file (SHA-256). Needs pypdf (pip install pypdf).

    python3 scripts/kwsp/third-schedule.py
"""

import hashlib
import json
import pathlib
import re
import sys

from pypdf import PdfReader

ROOT = pathlib.Path(__file__).resolve().parents[2]
PDF = ROOT / "docs/sources/kwsp/third-schedule-2025-10-01.pdf"
OUT = ROOT / "src/data/kwsp/2025-10.ts"
SHA256 = "c4904e44f0cb15a251a59e4f34c11a1ededa0868b962b2ebd9b81270285358b1"

digest = hashlib.sha256(PDF.read_bytes()).hexdigest()
if digest != SHA256:
    sys.exit(f"unexpected PDF ({digest}) - new schedule? update SHA256 and re-check by hand")

text = "\n".join(p.extract_text() or "" for p in PdfReader(str(PDF)).pages)
num = lambda s: round(float(s.replace(",", "")) * 100)  # sen
ROW = re.compile(r"From\s+([\d,]+\.\d\d)\s+to\s+([\d,]+\.\d\d)\s+(NIL|[\d,]+\.\d\d)\s+(NIL|[\d,]+\.\d\d)\s+(NIL|[\d,]+\.\d\d)")

parts = {}
for m in re.finditer(r"PART ([A-F])\s*\n(.*?)(?=PART [A-F]\s*\n|\Z)", text, re.S):
    rows = []
    for a, b, er, ee, tot in ROW.findall(m.group(2)):
        er, ee, tot = (0 if v == "NIL" else num(v) for v in (er, ee, tot))
        if er + ee != tot:
            sys.exit(f"Part {m.group(1)} {a}-{b}: {er}+{ee} != {tot}")
        rows.append([num(b), er, ee])  # band upper bound (sen), employer, employee
    if rows:
        parts[m.group(1)] = rows

for part, rows in parts.items():
    # Bands must be contiguous: each starts 1 sen above the previous upper bound.
    uppers = [r[0] for r in rows]
    if uppers != sorted(uppers) or uppers[-1] != 2_000_000:
        sys.exit(f"Part {part}: bands not increasing or not ending at RM20,000.00")
    print(f"Part {part}: {len(rows)} bands, last {rows[-1]}")

OUT.write_text(
    "// GENERATED by scripts/kwsp/third-schedule.py - do not edit.\n"
    "// KWSP Third Schedule (EPF Act 1991), effective October 2025 wages.\n"
    f"// Source PDF: docs/sources/kwsp/third-schedule-2025-10-01.pdf (sha256 {SHA256}).\n"
    "// Each band: [upper bound of wages in sen, employer RM in sen, employee RM in sen];\n"
    "// a band covers wages from the previous upper bound + 1 sen. Up to RM20,000.00 only;\n"
    "// above that and for Part F the contribution is a percentage (see src/lib/kwsp.ts).\n"
    f"export const THIRD_SCHEDULE: Record<string, [number, number, number][]> = {json.dumps(parts, separators=(',', ':'))};\n"
)
print("wrote", OUT)
