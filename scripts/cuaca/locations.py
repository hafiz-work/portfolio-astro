#!/usr/bin/env python3
"""Generate src/data/cuaca-lokasi.ts - MET Malaysia forecast locations for /ramalan-cuaca.

MET's list (api.data.gov.my/weather/forecast) has ids and names only - no coordinates.
Plan B (Open-Meteo) needs lat/lng, so each name is geocoded once with Open-Meteo's
geocoding API. Matching is strict on purpose - a wrong coordinate would show another
place's weather: exact name (case/accent-insensitive), country MY, a populated-place or
admin feature code. States (St...) take their capital (PPLA inside that state). No
match -> no coordinates -> that location has no Plan B (only the stored copy).

Run: python3 scripts/cuaca/locations.py   (never edit the generated file by hand)
"""
import json
import time
import unicodedata
import urllib.parse
import urllib.request
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "src/data/cuaca-lokasi.ts"
MET = "https://api.data.gov.my/weather/forecast/"
GEO = "https://geocoding-api.open-meteo.com/v1/search"
TYPES = {"St": "Negeri", "Dv": "Bahagian (Sarawak)", "Ds": "Daerah", "Tn": "Bandar", "Rc": "Rekreasi"}
PLACE = ("PPL", "ADM")


def get(url: str):
    req = urllib.request.Request(url, headers={"User-Agent": "hafizbahtiar.com cuaca-lokasi generator"})
    with urllib.request.urlopen(req, timeout=60) as res:
        return json.load(res)


def norm(s: str) -> str:
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode()
    return " ".join(s.lower().replace("-", " ").split())


def geocode(name: str, kind: str):
    q = urllib.parse.urlencode({"name": name, "count": 10, "countryCode": "MY", "language": "ms"})
    results = get(f"{GEO}?{q}").get("results") or []
    for r in results:
        if r.get("country_code") != "MY":
            continue
        code = r.get("feature_code") or ""
        if kind == "St":
            # State -> its capital: PPLA whose admin1 is the state.
            if code == "PPLA" and norm(r.get("admin1", "")) == norm(name):
                return r
        elif norm(r["name"]) == norm(name) and code.startswith(PLACE):
            return r
    return None


def main():
    rows = get(MET)
    seen: dict[str, str] = {}
    for r in rows:
        loc = r["location"]
        seen.setdefault(loc["location_id"], loc["location_name"])
    out = []
    for lid, name in sorted(seen.items()):
        kind = lid[:2]
        if kind not in TYPES:
            continue
        hit = None
        try:
            hit = geocode(name, kind)
        except Exception as e:  # network hiccup -> no Plan B for this one, not a crash
            print(f"  ! {lid} {name}: {e}")
        time.sleep(0.15)
        item = {"id": lid, "name": name, "type": TYPES[kind]}
        if hit:
            item |= {"lat": round(hit["latitude"], 4), "lng": round(hit["longitude"], 4)}
        out.append(item)
    with_coords = sum("lat" in i for i in out)
    assert len(out) > 300, f"only {len(out)} MET locations - API changed?"
    lines = [
        "// GENERATED by scripts/cuaca/locations.py - do not edit by hand.",
        "// MET Malaysia forecast locations (id, name, type). lat/lng only where Open-Meteo's",
        "// geocoder matched the exact name - those locations have the Open-Meteo Plan B.",
        f"// {len(out)} locations, {with_coords} with coordinates.",
        "export interface Lokasi {",
        "  id: string;",
        "  name: string;",
        "  type: string;",
        "  lat?: number;",
        "  lng?: number;",
        "}",
        "",
        "export const LOKASI: Lokasi[] = [",
        *[f"  {json.dumps(i, ensure_ascii=False)}," for i in out],
        "];",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(OUT.parents[2])}: {len(out)} locations, {with_coords} with coordinates")


if __name__ == "__main__":
    main()
